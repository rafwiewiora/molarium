// Generate the readable tables solely from frozen, hash-verified measurements.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {gunzipSync} from 'node:zlib';
import {summarize} from './metrics.mjs';
const base=new URL('./results/',import.meta.url);
const sha=b=>createHash('sha256').update(b).digest('hex');
async function artifact(directory,name){
  const manifest=JSON.parse(await readFile(new URL(`${directory}/manifest.json`,base)));
  const entry=manifest.files.find(f=>f.name===`${name}.gz`);
  if(!entry)throw new Error(`Missing artifact ${directory}/${name}`);
  const bytes=await readFile(new URL(`${directory}/${entry.name}`,base));
  if(sha(bytes)!==entry.sha256)throw new Error('Compressed evidence hash mismatch');
  const raw=gunzipSync(bytes);
  if(sha(raw)!==entry.uncompressedSha256)throw new Error('Raw evidence hash mismatch');
  return JSON.parse(raw);
}
const index=JSON.parse(await readFile(new URL('./results/runs.json',import.meta.url)));
const groups=[];
for(const run of index.runs){
  const measured=await artifact(run.directory,run.actual),score=await artifact(run.scoreDirectory||run.directory,run.score);
  if(score.sources.actualSha256!==sha(gunzipSync(await readFile(new URL(`${run.directory}/${run.actual}.gz`,base)))))
    throw new Error(`Score belongs to another result: ${run.label}`);
  groups.push({...run,scoreFilename:run.score,measured,score});
}
const fmt=n=>Number(n).toExponential(2);
const timing=n=>Number(n).toFixed(1);
const lines=['# Measured results','','Generated by `node benchmarks/simulation/build-report.mjs`. Raw energy/force vectors,',
  'all timing repetitions, input packets, hashes, and failed attempts are retained in gzip JSON.',
  'These are implementation comparisons, not force-field validation against experiment.','',
  '## Energy and force agreement','','Every row uses all 47 cases, including the two 500 Å translation stress pairs.',
  'The primary gate uses f32-rounded inputs; per-case original-input and quantization',
  'comparisons remain in each score artifact. All forces are included.','',
  '| Hardware / implementation | Passing cases | Median of case-median symmetric atom error | Largest force relative RMS |',
  '| --- | ---: | ---: | ---: |'];
for(const {label,score} of groups){
  if(score.gate.total!==47)throw new Error('This results table requires the complete 47-case suite');
  lines.push(`| ${label} | ${score.gate.passedCases}/${score.gate.total} | ${fmt(score.gate.medianOfCaseMedianSymmetricAtomError)} | ${fmt(score.gate.maximumForceRelativeRms)} |`);
}
lines.push('','## Throughput','','Median ns/day; brackets contain the P05–P95 spread of five warmed samples.',
  'All use 250-step jobs/blocks, 1 fs, 300 K and friction 1/ps. The column headings',
  'identify different timing scopes and integrators: these columns must not be',
  'converted into claims of matched kernel speedups. See the [protocol](../README.md#speed-protocol-and-interpretation).','');
const timed=groups.filter(g=>g.measured.cases.some(c=>c.performance));
lines.push(`| Workload | ${timed.map(g=>g.label+'; '+(g.measured.platform?'resident Context':'production job')).join(' | ')} |`,
  `| --- | ${timed.map(()=>'---:').join(' | ')} |`);
for(const c of groups[0].measured.cases.filter(c=>c.performance)){
  const cells=timed.map(g=>{
    const p=g.measured.cases.find(r=>r.id===c.id)?.performance?.dynamics;
    if(!p)return 'not measured';
    if(p.samples.length!==5)throw new Error('Headline table requires five samples');
    const s=summarize(p.samples.map(v=>v.nsPerDay));
    return `${timing(s.median)} [${timing(s.p05)}–${timing(s.p95)}]`;
  });
  lines.push(`| ${c.id} | ${cells.join(' | ')} |`);
}
lines.push('','## Single-point latency','','Median milliseconds for energy plus all Cartesian forces. The same scope distinction',
  'applies: browser jobs include fresh packing/allocation and transfers; native Contexts are resident.','',
  `| Workload | ${timed.map(g=>g.label).join(' | ')} |`,
  `| --- | ${timed.map(()=>'---:').join(' | ')} |`);
for(const c of groups[0].measured.cases.filter(c=>c.performance)){
  lines.push(`| ${c.id} | ${timed.map(g=>{
    const p=g.measured.cases.find(r=>r.id===c.id)?.performance?.energy;
    return p?timing(summarize(p.samples.map(v=>v.msPerJob)).median):'not measured';
  }).join(' | ')} |`);
}
lines.push('','## Hardware and raw artifacts','');
for(const {label,directory,actual,scoreDirectory,score:scoreData,...g} of groups){
  const env=g.measured.environment;
  lines.push(`- ${label}: [raw results](${directory}/${actual}.gz), [score](${scoreDirectory||directory}/${g.scoreFilename}.gz), [manifest](${directory}/manifest.json).`);
  if(env.browser)lines.push(`  ${env.browser.userAgent}; adapter ${JSON.stringify(env.browser.adapter)}.`);
  else lines.push(`  OpenMM ${env.openmm}; ${env.os}; Python ${env.python.split('\n')[0]}.`);
}
lines.push('','M1 Pro measurements used the local interactive workstation; CPU/background activity',
  'was not isolated. L4 measurements used the existing dedicated benchmark VM with no',
  'concurrent GPU benchmark jobs. Power/thermal locking was not imposed. No results',
  'are claimed yet for AMD, Intel, A100/H100, other Apple generations, or consumer RTX GPUs.','',
  'Executable file hashes pin the tested source snapshots. A reported Git commit is',
  'the checkout base, not a claim that all measured worktree files were unchanged.','',
  '## Failed and superseded attempts','',
  '- [Initial M1 Pro run](m1pro-regression-before/manifest.json): 44/46 passed; detected serial f32 energy-summation loss.',
  '- [Corrected original suite](m1pro-regression-after/manifest.json): 46/46 passed with unchanged thresholds.',
  '- The complete expanded suite above uses explicit DHFR OBC radii and sufficient neighbor capacity.',
  '- Missing CUDA plugins or unavailable hardware adapters are setup failures, never passing accuracy/speed results.','');
const output=new URL('./results/README.md',import.meta.url);
await writeFile(output,lines.join('\n'));
console.log(`Generated ${output.pathname}`);
