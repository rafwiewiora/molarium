const files = [];
for (const path of reviewedFiles) {
  const file = Bun.file(resolve(root, path));
  if (!(await file.exists())) throw new Error(`Missing reviewed file: ${path}`);
  const bytes = await file.arrayBuffer();
  const hasher = new Bun.CryptoHasher('sha256');
  hasher.update(bytes);
  files.push({ path, bytes: bytes.byteLength, sha256:hasher.digest('hex') });
}

const manifest = {
  schema:1,
  product:'Molarium Local Lab',
  policy:'local-only-v1',
  algorithm:'SHA-256',
  scope:'Reviewed executable sources and compact runtime assets. The per-session runtime configuration is generated by the reviewed server and verified separately. Large ONNX model hashes are recorded by their pinned model manifests and model cards.',
  files,
};
await Bun.write(resolve(root, 'local-lab-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`Wrote local-lab-manifest.json with ${files.length} reviewed files`);
